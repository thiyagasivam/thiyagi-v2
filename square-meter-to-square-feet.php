<script>
function updateConversion() {
  const sqmValue = parseFloat(document.getElementById('sqmValue').value);
  const sqftResult = document.getElementById('sqftResult');
  const copyBtn = document.getElementById('copyBtn');
  
  if (isNaN(sqmValue) || sqmValue < 0) {
    sqftResult.value = '';
    copyBtn.classList.add('hidden');
    return;
  }
  
  // Convert square meters to square feet (1 m² = 10.7639 ft²)
  const sqftValue = sqmValue * 10.7639;
  
  // Format the result with appropriate decimal places
  let formattedResult;
  if (sqftValue >= 1000) {
    formattedResult = sqftValue.toFixed(1);
  } else if (sqftValue >= 100) {
    formattedResult = sqftValue.toFixed(2);
  } else {
    formattedResult = sqftValue.toFixed(3);
  }
  
  sqftResult.value = formattedResult;
  copyBtn.classList.remove('hidden');
}

function copyResult() {
  const sqmValue = document.getElementById('sqmValue').value;
  const sqftResult = document.getElementById('sqftResult').value;
  const copyText = `${sqmValue} square meters = ${sqftResult} square feet`;
  
  navigator.clipboard.writeText(copyText).then(() => {
    const copySuccess = document.getElementById('copySuccess');
    copySuccess.classList.remove('hidden');
    setTimeout(() => {
      copySuccess.classList.add('hidden');
    }, 3000);
  });
}

document.getElementById('sqmValue').addEventListener('input', updateConversion);
document.getElementById('copyBtn').addEventListener('click', copyResult);

// Autofocus and demo value
window.addEventListener('DOMContentLoaded', () => {
  document.getElementById('sqmValue').focus();
  document.getElementById('sqmValue').value = 100;
  updateConversion();
});
</script>

