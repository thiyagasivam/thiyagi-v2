<script>
  // Conversion function: 1 hectare = 107639.1 square feet
  function convertSqftToHectare() {
    const sqftInput = document.getElementById('sqftValue');
    const hectareResult = document.getElementById('hectareResult');
    const copyBtn = document.getElementById('copyBtn');
    
    const sqftValue = parseFloat(sqftInput.value);
    
    if (isNaN(sqftValue) || sqftValue < 0) {
      hectareResult.value = '';
      copyBtn.classList.add('hidden');
      return;
    }
    
    const hectareValue = sqftValue / 107639.1;
    hectareResult.value = hectareValue.toFixed(8);
    copyBtn.classList.remove('hidden');
  }
  
  // Copy to clipboard function
  function copyResult() {
    const hectareResult = document.getElementById('hectareResult');
    const copySuccess = document.getElementById('copySuccess');
    
    if (hectareResult.value) {
      navigator.clipboard.writeText(hectareResult.value).then(() => {
        copySuccess.classList.remove('hidden');
        setTimeout(() => {
          copySuccess.classList.add('hidden');
        }, 2000);
      });
    }
  }
  
  // Event listeners
  document.getElementById('sqftValue').addEventListener('input', convertSqftToHectare);
  document.getElementById('copyBtn').addEventListener('click', copyResult);
  
  // Initialize conversion
  convertSqftToHectare();
</script>

